    RELOAD_SUCCESS, RELOAD_UNAVAILABLE, SOURCE_ABSENT, SOURCE_EMPTY, SOURCE_DATA_NOT_LOADED,
    SOURCE_LIST_HEADER, SOURCE_LIST_ENTRY, SOURCE_LIST_FOOTER, SOURCE_INFO_HEADER, SOURCE_INFO_ENTRY,
    SOURCE_INFO_NAMES, SOURCE_INFO_VALUE, SOURCE_INFO_FOOTER,
    SOURCE_INFO_NONE, SOURCE_INFO_PLACEHOLDERS,
    SOURCE_GIVE_SUBMITTED, SOURCE_GIVE_SUBMITTED_STABLE, SOURCE_REMOVE_SUBMITTED,
